"""Build assets/i18n/en.js and fr.js from dev/i18n/translations.json.
translations.json maps the Hebrew source text -> [English, French].
Run extract.py first to see which Hebrew strings still have no translation."""
import json, re, os
D = os.path.dirname(os.path.abspath(__file__))
norm = lambda s: re.sub(r'\s+', ' ', s).strip()
tr = json.load(open(os.path.join(D, 'translations.json')))
out = {'en': {}, 'fr': {}}
bad = []
for k, (en, fr) in tr.items():
    k = norm(k)
    out['en'][k] = en; out['fr'][k] = fr
    for v in (en, fr):
        if sorted(set(re.findall(r'\{\d\}', k))) != sorted(set(re.findall(r'\{\d\}', v))): bad.append((k, v))
        for ph in ('{W}', '{P}', '{D}', '{N}'):
            if (ph in k) != (ph in v): bad.append((k, v))
if bad: print('PLACEHOLDER MISMATCH', bad[:10])
dest = os.path.join(D, '..', '..', 'assets', 'i18n')
os.makedirs(dest, exist_ok=True)
for lang, d in out.items():
    p = os.path.join(dest, lang + '.js')
    open(p, 'w').write('/* ' + lang + ' translations — generated by dev/i18n/merge.py; key = Hebrew source text */\nwindow.MIREL_I18N = ' + json.dumps(d, ensure_ascii=False, indent=0) + ';\n')
    print(lang, len(d), os.path.getsize(p))
