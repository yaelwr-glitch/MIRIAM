  /* ---------- Render AI text (very small markdown subset, safely escaped) ---------- */
  function renderAnswer(text) {
    const lines = M.esc(text).split(/\r?\n/);
    let html = "", inList = false;
    lines.forEach((ln) => {
      const t = ln.trim();
      const li = t.match(/^([-*•]|\d+[.)])\s+(.*)$/);
      if (li) { if (!inList) { html += "<ul>"; inList = true; } html += `<li>${bold(li[2])}</li>`; return; }
      if (inList) { html += "</ul>"; inList = false; }
      if (!t) return;
      const h = t.match(/^#{1,4}\s+(.*)$/);
      html += h ? `<h3>${bold(h[1])}</h3>` : `<p>${bold(t)}</p>`;
    });
    if (inList) html += "</ul>";
    return html;
  }
  function bold(s) { return s.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>"); }

